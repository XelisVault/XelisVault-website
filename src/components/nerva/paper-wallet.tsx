/* ───────────────── self-verification panel ───────────────── */

function VerifyPanel({ wallet }: { wallet: NervaWallet }) {
  const rows = useMemo(() => {
    const dec = decodeAddress(wallet.address)
    const restored = walletFromMnemonic(wallet.mnemonic)
    return [
      { label: 'address shape', value: `${wallet.address.length} chars, starts “${wallet.address.slice(0, 6)}…”`, ok: wallet.address.length === 97 && wallet.address.startsWith('NV') },
      { label: 'decoded prefix', value: dec ? `0x${dec.tag.toString(16)} (standard)` : '—', ok: dec !== null && dec.tag === 0x3800n },
      { label: 'keccak checksum', value: dec ? 'verified on decode' : '—', ok: dec !== null },
      { label: 'decoded keys', value: dec ? 'byte-identical to generated keys' : '—', ok: dec !== null && bytesToHex(dec.spendPub) === bytesToHex(wallet.spendPub) && bytesToHex(dec.viewPub) === bytesToHex(wallet.viewPub) },
      { label: 'view = H(spend)', value: 'sc_reduce32(keccak(spend)) ✓', ok: bytesToHex(wallet.view) === bytesToHex(scReduce32(keccak(wallet.spend))) },
      { label: 'mnemonic restore', value: restored ? 'same address from the 25 words' : '—', ok: restored !== null && restored.address === wallet.address },
    ]
  }, [wallet])
  return (
    <div className="rounded-md border border-white/8 bg-white/[0.02] overflow-hidden">
      <div className="px-4 py-3 border-b border-white/8 flex items-center gap-2.5">
        <ShieldCheck className="w-4 h-4 text-[oklch(0.72_0.12_160)]" />
        <span className="font-mono text-[10px] uppercase tracking-[0.18em] text-white/70">self-verification — run live in your browser</span>
      </div>
      <div className="divide-y divide-white/6">
        {rows.map((r) => (
          <div key={r.label} className="px-4 py-2.5 flex items-center gap-3">
            <span className="font-mono text-[9.5px] uppercase tracking-[0.14em] text-[oklch(0.55_0.01_250)] w-[128px] shrink-0">{r.label}</span>
            <span className="flex-1 min-w-0 font-mono text-[11px] text-white/75 truncate">{r.value}</span>
            {r.ok
              ? <Check className="w-3.5 h-3.5 text-[oklch(0.72_0.12_160)] shrink-0" />
              : <ShieldAlert className="w-3.5 h-3.5 text-[oklch(0.7_0.15_45)] shrink-0" />}
          </div>
        ))}
      </div>
    </div>
  )
}

