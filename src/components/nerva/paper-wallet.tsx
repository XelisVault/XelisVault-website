function CopyChip({ value, label }: { value: string; label?: string }) {
  const [copied, setCopied] = useState(false)
  return (
    <button
      type="button"
      onClick={() => { void copyText(value).then((ok) => { if (ok) { setCopied(true); setTimeout(() => setCopied(false), 1600) } }) }}
      title={`Copy ${label ?? 'value'}`}
      className="no-print inline-flex items-center gap-1.5 h-7 px-2.5 rounded-sm border border-white/10 bg-white/[0.03] hover:border-[oklch(0.78_0.06_237)]/40 hover:bg-[oklch(0.78_0.06_237)]/[0.06] transition-colors font-mono text-[9.5px] uppercase tracking-[0.12em] text-white/60 hover:text-white/90"
    >
      {copied ? <Check className="w-3 h-3 text-[oklch(0.72_0.12_160)]" /> : <Copy className="w-3 h-3" />}
      {copied ? 'copied' : (label ?? 'copy')}
    </button>
  )
}

function InfoCard({ icon: Icon, children, tone = 'neutral' }: {
  icon: React.ElementType
  children: React.ReactNode
  tone?: 'neutral' | 'warn' | 'ok'
}) {
  const border = tone === 'warn' ? 'border-[oklch(0.7_0.15_45)]/30' : tone === 'ok' ? 'border-[oklch(0.72_0.12_160)]/30' : 'border-white/8'
  const bg = tone === 'warn' ? 'bg-[oklch(0.7_0.15_45)]/[0.06]' : tone === 'ok' ? 'bg-[oklch(0.72_0.12_160)]/[0.05]' : 'bg-white/[0.02]'
  return (
    <div className={`rounded-md border ${border} ${bg} px-4 py-3.5 flex gap-3 items-start`}>
      <Icon className={`w-4 h-4 mt-0.5 shrink-0 ${tone === 'warn' ? 'text-[oklch(0.75_0.15_60)]' : tone === 'ok' ? 'text-[oklch(0.72_0.12_160)]' : 'text-[oklch(0.78_0.06_237)]'}`} />
      <div className="text-[12.5px] leading-relaxed text-[oklch(0.78_0.01_250)]">{children}</div>
    </div>
  )
}

